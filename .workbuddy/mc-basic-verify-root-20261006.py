checks=[]
def eq(name,left,right):
    d=left-right
    ok=all(S.simplify(v)==0 for v in d) if isinstance(d,S.MatrixBase) else S.simplify(d)==0
    assert ok,(name,d)
    checks.append(name)
def phi(name,A,P):
    eq(name+' initial',P.subs(t,0),S.eye(A.rows))
    eq(name+' ode',P.diff(t),A*P)
